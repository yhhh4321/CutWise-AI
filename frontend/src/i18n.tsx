/* ── Context ── */
interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  getLangLabel: (l: Lang) => string;
}
const I18nContext = createContext<I18nCtx>(null!);
export const useI18n = () => useContext(I18nContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem('lang') as Lang | null;
    return stored && LANGS.some((l) => l.code === stored) ? stored : 'zh';
  });

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('lang', l);
    setLangState(l);
  }, []);

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    let s = DICT[lang]?.[key] ?? DICT.zh?.[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.split(`{${k}}`).join(String(v));
      }
    }
    return s;
  }, [lang]);

  const getLangLabel = useCallback((l: Lang): string => {
    const entry = LANGS.find((x) => x.code === l);
    return entry ? entry.native : l;
  }, []);

  // 同步到 html lang 属性
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, getLangLabel }}>
      {children}
    </I18nContext.Provider>
  );
}

/* ── 导出 AI 语言的系统提示 ── */
export function getLangPrompt(lang: Lang): string {
  return DICT[lang]?.['ai.lang_prompt'] ?? DICT.zh['ai.lang_prompt'];
}
